#!/usr/bin/env bash

###############################################################################
# linux-update signing pipeline
#
# Purpose:
#   1. Discover generated packages (.deb/.rpm)
#   2. Generate SHA256SUMS
#   3. Export public GPG key
#   4. Sign SHA256SUMS -> SHA256SUMS.asc
#   5. Verify SHA256SUMS signature
#   6. Create detached signatures for all DEB packages (*.deb.sig)
#   7. Sign RPM packages using embedded RPM/OpenPGP signatures
#   8. (Optional) Sign DEB packages with dpkg-sig if available
#
# Output artifacts:
#
#   linux-update_VERSION.deb
#   linux-update_VERSION.deb.sig
#
#   linux-update-VERSION.rpm
#
#   SHA256SUMS
#   SHA256SUMS.asc
#
#   public.key
#
# Verification by users:
#
#   gpg --import public.key
#
#   gpg --verify SHA256SUMS.asc SHA256SUMS
#   sha256sum -c SHA256SUMS
#
#   gpg --verify package.deb.sig package.deb
#
#   rpm -Kv package.rpm
#
###############################################################################

# Exit immediately on error.
# Treat unset variables as errors.
# Fail pipelines when any command fails.
set -euo pipefail

# Read project version from version.txt
VERSION=$(<version.txt)

# Allow custom destination directory.
# If not provided, use the default release directory.
DIST_DIR="${1:-/mnt/c/Windows/Temp/v$VERSION}"

echo "linux-update signing system"
echo "Version: $VERSION"
echo "Directory: $DIST_DIR"

###############################################################################
# Sanity check
###############################################################################

if [ ! -d "$DIST_DIR" ]; then
    echo "ERROR: Directory not found: $DIST_DIR"
    exit 1
fi

cd "$DIST_DIR"

###############################################################################
# Step 1
# Discover packages generated by the build system.
###############################################################################

echo
echo "[1/9] Discover packages"

shopt -s nullglob

PACKAGES=( *.deb *.rpm )

if [ ${#PACKAGES[@]} -eq 0 ]; then
    echo "ERROR: No packages found"
    exit 1
fi

printf '  %s\n' "${PACKAGES[@]}"

###############################################################################
# Step 2
# Create SHA256SUMS.
#
# This file contains hashes of all release packages.
# Users can later run:
#
#   sha256sum -c SHA256SUMS
#
###############################################################################

echo
echo "[2/9] Create SHA256SUMS"

sha256sum "${PACKAGES[@]}" > SHA256SUMS

echo "Created SHA256SUMS"

###############################################################################
# Step 3
# Locate the GPG secret key used for signing.
#
# The key MUST exist in the current user's GPG keyring.
###############################################################################

echo
echo "[3/9] Locate GPG secret key"

KEY_ID=$(
    gpg --list-secret-keys --with-colons \
    | awk -F: '/^sec:/ {print $5; exit}'
)

if [ -z "$KEY_ID" ]; then
    echo "ERROR: No GPG secret key found"
    exit 1
fi

echo "Using key: $KEY_ID"

###############################################################################
# Step 4
# Export the public key.
#
# This file is distributed with releases so users can verify:
#
#   SHA256SUMS.asc
#   package.deb.sig
#
###############################################################################

echo
echo "[4/9] Export public key"

gpg \
    --armor \
    --export "$KEY_ID" \
    > public.key

echo "Created public.key"

###############################################################################
# Step 5
# Sign SHA256SUMS.
#
# Creates:
#
#   SHA256SUMS.asc
#
# This is the primary release signature.
###############################################################################

echo
echo "[5/9] Sign SHA256SUMS"

rm -f SHA256SUMS.asc

gpg \
    --local-user "$KEY_ID" \
    --armor \
    --detach-sign \
    SHA256SUMS

echo "Created SHA256SUMS.asc"

###############################################################################
# Step 6
# Verify the signature we just created.
#
# This acts as a sanity check during release creation.
###############################################################################

echo
echo "[6/9] Verify SHA256SUMS signature"

gpg \
    --verify \
    SHA256SUMS.asc \
    SHA256SUMS

echo "Signature verification OK"

###############################################################################
# Step 7
# Create detached signatures for DEB packages.
#
# Example:
#
#   linux-update_0.3.0.deb
#   linux-update_0.3.0.deb.sig
#
# Verification:
#
#   gpg --verify package.deb.sig package.deb
#
###############################################################################

echo
echo "[7/9] Create detached signatures"

for file in *.deb *.AppImage
do
    sigfile="${file}.sig"

    rm -f "$sigfile"

    echo "Signing $file"

    gpg \
        --local-user "$KEY_ID" \
        --detach-sign \
        "$file"

    gpg \
        --verify \
        "$sigfile" \
        "$file"

    echo "Verified $sigfile"
done

###############################################################################
# Step 8
# Sign RPM packages.
#
# This embeds an OpenPGP signature directly inside the RPM.
#
# Verification:
#
#   rpm -Kv package.rpm
#
###############################################################################

echo
echo "[8/9] RPM package signing"

if command -v rpm >/dev/null 2>&1; then

    for rpmfile in *.rpm
    do
        echo "Signing $rpmfile"

        rpm --addsign "$rpmfile"

        rpm -Kv "$rpmfile"

        echo "RPM signature verified"
    done

else
    echo "rpm command not found - skipped"
fi


###############################################################################
# Final summary
###############################################################################

echo
echo "Artifacts created:"

ls -lh \
    -- *.deb \
    *.rpm \
    *.sig \
    SHA256SUMS \
    SHA256SUMS.asc \
    public.key

echo
echo "Completed successfully"