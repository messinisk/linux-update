#!/usr/bin/env bash

###############################################################################
# Information
###############################################################################

info_apt() {

    while true
    do

        show_package_menu "APT Operations"

        case "$MENU_SELECTION" in

            1)
                update_apt
                ;;

            2)
                upgrade_apt
                ;;

            3)
                autoremove_apt
                ;;

            4)
                autoclean_apt
                ;;

            5)
                break
                ;;

        esac

    done
}

###############################################################################
# Update metadata
###############################################################################

update_apt() {
    sudo apt update
}

###############################################################################
# Upgrade packages
###############################################################################

upgrade_apt() {
    sudo apt full-upgrade
}

###############################################################################
# Remove unused dependencies
###############################################################################

autoremove_apt() {
    sudo apt autoremove
}

###############################################################################
# Clean package cache
###############################################################################

autoclean_apt() {
    sudo apt autoclean
}
